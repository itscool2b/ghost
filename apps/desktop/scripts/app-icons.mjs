// Regenerates every desktop icon from the logo geometry in @ghost/ui (logoPaths.ts):
//   app-icon.svg          macOS and PNG source: the macOS grid, an 824px body inset 100px
//   app-icon-windows.svg  icon.ico source: a full-bleed tile, small-variant logo (larger eyes)
//   tray.png              Windows notification area, 32px tile
//   tray-template.png     macOS menu bar template image, 36px black logo on transparency
// then rasterises them through the Tauri CLI. Run with: pnpm --filter @ghost/desktop icons
import { execSync } from "node:child_process";
import { copyFileSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  LOGO_PATH,
  LOGO_SMALL_PATH,
  LOGO_VIEWBOX,
} from "../../../packages/ui/src/graphite/logoPaths.ts";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const icons = join(app, "src-tauri", "icons");
const [vw, vh] = LOGO_VIEWBOX;

/** The logo scaled to `size` px wide (it is far wider than tall) and centred on (cx, cy). */
function logo(d, size, cx, cy, fill) {
  const scale = size / Math.max(vw, vh);
  const x = cx - (vw * scale) / 2;
  const y = cy - (vh * scale) / 2;
  const r = (n) => Math.round(n * 1000) / 1000;
  return `<path transform="translate(${r(x)} ${r(y)}) scale(${r(scale)})" fill="${fill}" fill-rule="evenodd" d="${d}"/>`;
}

const svg = (body, comment) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n` +
  `  <title>Ghost</title>\n  <!-- ${comment} Generated by scripts/app-icons.mjs. -->\n${body}\n</svg>\n`;

const sources = {
  "app-icon.svg": svg(
    [
      `  <rect x="100" y="100" width="824" height="824" rx="185" fill="#000000"/>`,
      `  <rect x="102" y="102" width="820" height="820" rx="183" fill="none" stroke="#2e2e2e" stroke-width="4"/>`,
      `  ${logo(LOGO_PATH, 640, 512, 512, "#ededed")}`,
    ].join("\n"),
    "The macOS app icon: the wing in fg-1 on a black tile that follows the macOS grid (an 824px body inset 100px, radius 185), so the system shadow has room.",
  ),
  "app-icon-windows.svg": svg(
    [
      `  <rect width="1024" height="1024" rx="192" fill="#000000"/>`,
      `  <rect x="3" y="3" width="1018" height="1018" rx="189" fill="none" stroke="#2e2e2e" stroke-width="6"/>`,
      `  ${logo(LOGO_SMALL_PATH, 820, 512, 512, "#ededed")}`,
    ].join("\n"),
    "The Windows icon (icon.ico): the small-variant logo on a full-bleed black tile, so the eyes stay open in the 16, 24 and 32px frames.",
  ),
};

const work = mkdtempSync(join(tmpdir(), "auracode-icons-"));
const trays = {
  "tray-windows.svg": svg(
    [
      `  <rect width="1024" height="1024" rx="192" fill="#000000"/>`,
      `  ${logo(LOGO_SMALL_PATH, 880, 512, 512, "#ededed")}`,
    ].join("\n"),
    "Windows tray icon source.",
  ),
  "tray-macos.svg": svg(
    `  ${logo(LOGO_SMALL_PATH, 1000, 512, 512, "#000000")}`,
    "macOS menu bar template source; only alpha is used.",
  ),
};

try {
  for (const [name, text] of Object.entries(sources)) writeFileSync(join(icons, name), text);
  for (const [name, text] of Object.entries(trays)) writeFileSync(join(work, name), text);
  // One quoted command line: pnpm is a .cmd shim on Windows, which only a shell can start.
  const tauri = (...args) =>
    execSync(["pnpm exec tauri icon", ...args.map((a) => JSON.stringify(a))].join(" "), {
      cwd: app,
      stdio: "inherit",
    });
  tauri(join(icons, "app-icon.svg"), "--output", icons);
  // Ghost ships on Windows and macOS only.
  for (const platform of ["android", "ios"]) {
    rmSync(join(icons, platform), { recursive: true, force: true });
  }
  const windows = join(work, "windows");
  tauri(join(icons, "app-icon-windows.svg"), "--output", windows);
  copyFileSync(join(windows, "icon.ico"), join(icons, "icon.ico"));
  for (const [source, size, target] of [
    ["tray-windows.svg", 32, "tray.png"],
    ["tray-macos.svg", 36, "tray-template.png"],
  ]) {
    const out = join(work, target);
    tauri(join(work, source), "--output", out, "--png", String(size));
    copyFileSync(join(out, `${size}x${size}.png`), join(icons, target));
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
